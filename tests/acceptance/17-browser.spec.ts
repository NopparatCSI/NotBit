import { expect, test } from "vitest";
import { openBrowser,browserWallet,signIn,uiExpect } from "./browser-wallet";
import { state,index,client,imageBytes,service,record } from "./environment";

test("17 UI: listing, chat, offer, deposit, images, delivery, receipt and exact settlement",async()=>{
  const browser=await openBrowser();
  try{
    const {page:seller}=await browserWallet(browser,"seller"),{page:buyer}=await browserWallet(browser,"buyer");
    await signIn(seller);await signIn(buyer);
    await seller.goto(`${state.appUrl}/sell`);
    const form=seller.locator('form').first();const title=`UI acceptance ${crypto.randomUUID().slice(0,8)}`;
    await form.getByLabel("Item name",{exact:true}).fill(title);
    await form.locator('select[name="gameSlug"]').selectOption("warframe");
    await form.getByLabel("Price in Sepolia ETH",{exact:true}).fill("0.001");
    await form.getByLabel("Server or region",{exact:true}).fill("Asia");
    await form.getByLabel("Delivery method",{exact:true}).fill("In-game trade");
    await form.getByLabel("Item description",{exact:true}).fill("Actual browser acceptance listing");
    const listingResponse=seller.waitForResponse(r=>r.url().endsWith("/api/v1/listings")&&r.request().method()==="POST");
    await form.getByRole("button",{name:"Publish listing",exact:true}).click();
    const listing=await (await listingResponse).json();expect(listing.error).toBeUndefined();
    await buyer.goto(`${state.appUrl}/buy/listings/${listing.data.id}`);
    await buyer.getByRole("button",{name:/chat|contact|message/i}).click();
    await buyer.waitForURL("**/trade/*");const roomUrl=buyer.url();const conversationId=new URL(roomUrl).pathname.split("/").pop()!;
    await buyer.getByLabel("Message",{exact:true}).fill("Ready for browser acceptance delivery");
    await buyer.getByRole("button",{name:"Send message",exact:true}).click();
    await seller.goto(roomUrl);await uiExpect(seller.getByText("Ready for browser acceptance delivery",{exact:true})).toBeVisible();
    await seller.getByRole("tab",{name:"Deal summary",exact:true}).click();
    await seller.getByLabel("Buyer character",{exact:true}).fill("UI Buyer");await seller.getByLabel("Seller character",{exact:true}).fill("UI Seller");
    await seller.getByLabel("Meeting time (your local time)",{exact:true}).fill(new Date(Date.now()+3600_000).toISOString().slice(0,16));
    await seller.getByRole("button",{name:"Review offer",exact:true}).click();
    await uiExpect(seller.getByRole("button",{name:"Sign and send offer",exact:true})).toBeVisible();
    const offerResponse=seller.waitForResponse(r=>r.url().endsWith("/offers")&&r.request().method()==="POST");
    await seller.getByRole("button",{name:"Sign and send offer",exact:true}).click();
    const offer=await(await offerResponse).json();expect(offer.error).toBeUndefined();
    await buyer.reload();await buyer.getByRole("tab",{name:"Deal summary",exact:true}).click();
    await buyer.getByRole("button",{name:"Deposit 0.001 ETH",exact:true}).click();
    await uiExpect.poll(async()=>Number(await client.getBalance({address:state.escrowAddress})),{timeout:20000}).toBeGreaterThan(0);
    await uiExpect.poll(async()=>{const rows=await service.from("funding_attempts").select("tx_hash").eq("offer_id",offer.data.id);return rows.data?.length??0;},{timeout:20000}).toBe(1);
    await index();await seller.reload();await seller.getByRole("tab",{name:"Evidence",exact:true}).click();
    const sellerBefore=await client.getBalance({address:state.roles.seller});const treasuryBefore=await client.getBalance({address:state.roles.treasury});
    const file={name:"acceptance.png",mimeType:"image/png",buffer:await imageBytes()};
    await seller.getByLabel("Evidence images",{exact:true}).setInputFiles(file);
    await seller.getByRole("button",{name:"Upload evidence",exact:true}).click();
    await uiExpect(seller.getByRole("button",{name:"Confirm delivery",exact:true})).toBeEnabled({timeout:20000});
    await seller.getByRole("button",{name:"Confirm delivery",exact:true}).click();
    await uiExpect.poll(async()=>{await index();return(await service.from("orders").select("status").eq("id",offer.data.id).single()).data?.status;},{timeout:20000}).toBe("DELIVERED");
    await buyer.reload();await buyer.getByRole("tab",{name:"Evidence",exact:true}).click();
    await buyer.getByLabel("Evidence images",{exact:true}).setInputFiles(file);await buyer.getByRole("button",{name:"Upload evidence",exact:true}).click();
    await uiExpect(buyer.getByRole("button",{name:"Confirm receipt",exact:true})).toBeVisible({timeout:20000});
    await uiExpect(buyer.getByRole("button",{name:"Confirm receipt",exact:true})).toBeDisabled();
    await buyer.getByRole("checkbox").check();await buyer.getByRole("button",{name:"Confirm receipt",exact:true}).click();
    await uiExpect.poll(async()=>{await index();return(await service.from("orders").select("status").eq("id",offer.data.id).single()).data?.status;},{timeout:20000}).toBe("RELEASED");
    const delivery=await service.from("chain_events").select("tx_hash").eq("event_name","DeliveryConfirmed").eq("payload->>orderId",offer.data.signedOffer.orderId).single();
    const tx=await client.getTransactionReceipt({hash:delivery.data!.tx_hash});
    expect(await client.getBalance({address:state.roles.seller})-sellerBefore+tx.gasUsed*tx.effectiveGasPrice).toBe(950000000000000n);
    expect(await client.getBalance({address:state.roles.treasury})-treasuryBefore).toBe(50000000000000n);
    await uiExpect(buyer.getByText("RELEASED",{exact:true})).toBeVisible({timeout:20000});
    await uiExpect(buyer.getByRole("button",{name:"Confirm receipt",exact:true})).toHaveCount(0);
    await buyer.screenshot({path:".runtime/acceptance/17-browser-settled.png",fullPage:true});
    record("17-browser",{passed:true,provider:"deterministic EIP-1193 provider",orderId:offer.data.id,conversationId});
  }finally{await browser.close();}
});
